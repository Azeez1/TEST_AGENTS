"""
VOICE_TEAM Factory — Post-Deploy Setup Validator

Smoke-tests a firm's setup BEFORE real calls arrive:
  1. Loads the firm.yml
  2. Generates a synthetic test email intent from a mock call
  3. Runs the SAME validation rules the voice_email_gate.ps1 hook enforces
     (no vendor leaks, required sections, [Firm Name] subject prefix)
  4. Optionally also creates a real test calendar event you can delete after

If any validation fails, the firm is NOT demo-ready. Fix and re-run.

Usage:
    python validate_firm_setup.py memory/firms/sterling_legal.yml
    python validate_firm_setup.py memory/firms/sterling_legal.yml --create-test-calendar

Author: VOICE_TEAM Factory
"""

