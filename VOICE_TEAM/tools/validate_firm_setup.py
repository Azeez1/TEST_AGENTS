REPO_ROOT = Path(__file__).resolve().parents[2]
VOICE_TEAM = REPO_ROOT / "VOICE_TEAM"


# --- Validation rules (mirror voice_email_gate.ps1) ----------------------

FORBIDDEN_VENDOR_TERMS = [
    "retell", "retellai", "dashboard.retellai",
    "gpt-realtime", "openai-realtime",
    "11labs", "elevenlabs", "cartesia", "minimax", "deepgram", "twilio",
]
REQUIRED_SECTIONS = ["Caller", "Incident", "Action Required"]
SUBJECT_PREFIX_RE = re.compile(r"^\[[^\]]+\]")


def find_vendor_term(text: str) -> str | None:
    low = (text or "").lower()
    for term in FORBIDDEN_VENDOR_TERMS:
        if term in low:
            return term
    return None


def validate_intent(intent: dict) -> tuple[bool, list[str], list[str]]:
    """Return (passed, errors, warnings)."""
    errors: list[str] = []
    warnings: list[str] = []
    email = intent.get("email", {})
    subject = email.get("subject", "")
    body = email.get("body_markdown", "")
    to = email.get("to", "")

    # 1. Vendor leak in subject
    v = find_vendor_term(subject)
    if v:
        errors.append(f"Subject contains forbidden vendor term: '{v}'")

    # 2. Vendor leak in body
    v = find_vendor_term(body)
    if v:
        errors.append(f"Body contains forbidden vendor term: '{v}' (breaks white-label)")

    # 3. Subject prefix
    if not SUBJECT_PREFIX_RE.match(subject):
        errors.append(f"Subject must start with '[<Firm Name>]'. Got: '{subject}'")

    # 4. Required sections
    body_low = body.lower()
    for section in REQUIRED_SECTIONS:
        if section.lower() not in body_low:
            errors.append(f"Body missing required section: '{section}'")

    # 5. Recipient sanity
    if not to or "@" not in to:
        errors.append(f"Email recipient is invalid: '{to}'")

    # Soft warnings
    if len(body) > 8000:
        warnings.append(f"Body is long ({len(body)} chars) — attorneys may skim past key info")
    if len(body) < 400:
        warnings.append(f"Body is short ({len(body)} chars) — probably missing structured data")
    if not email.get("urls", {}).get("recording"):
        warnings.append("No recording URL in email.urls.recording — attorneys can't listen")

    return len(errors) == 0, errors, warnings


