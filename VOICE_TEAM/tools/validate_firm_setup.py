# --- Main ----------------------------------------------------------------

def main():
    if len(sys.argv) < 2:
        print("Usage: python validate_firm_setup.py <firm.yml path> [--create-test-calendar]", file=sys.stderr)
        sys.exit(1)

    firm_path = Path(sys.argv[1])
    if not firm_path.is_absolute():
        firm_path = (Path.cwd() / firm_path).resolve()
    if not firm_path.exists():
        print(f"FATAL: firm.yml not found at {firm_path}", file=sys.stderr)
        sys.exit(1)

    firm_doc = yaml.safe_load(firm_path.read_text(encoding="utf-8"))
    firm = firm_doc["firm"]
    print(f"\n=== Validating setup: {firm['name']} ({firm['slug']}) ===\n")

    # Step 1: deployment artifact must exist
    deploy_artifact = VOICE_TEAM / "outputs" / "deployments" / f"{firm['slug']}_s2s.json"
    deploy_artifact_alt = VOICE_TEAM / "outputs" / "deployments" / f"{firm['slug']}.json"
    if not deploy_artifact.exists() and not deploy_artifact_alt.exists():
        print(f"  [FAIL] No deployment artifact found. Run deploy first.")
        sys.exit(1)
    print(f"  [PASS] Deployment artifact exists")

    # Step 2: firm.yml has required fields
    required_top_keys = ["firm", "retell", "intake", "post_call_analysis"]
    missing_keys = [k for k in required_top_keys if k not in firm_doc]
    if missing_keys:
        print(f"  [FAIL] firm.yml missing top-level sections: {missing_keys}")
        sys.exit(1)
    print(f"  [PASS] firm.yml has all required top-level sections")

    # Step 3: phone number is bound
    phone = firm_doc.get("retell", {}).get("phone_number") or ""
    if not phone.startswith("+"):
        print(f"  [FAIL] Phone number not in E.164 format: '{phone}'")
        sys.exit(1)
    print(f"  [PASS] Phone number in E.164 format: {phone}")

    # Step 4: generate synthetic email intent + validate
    print(f"\n  Generating synthetic email intent for validation...")
    fields = fake_call_fields(firm)
    slot_dt = datetime.now(tz=timezone.utc) + timedelta(days=1)
    try:
        result = build_email_intent(firm_doc, fields, slot_dt, fields["call_id"], dry_run=True)
        intent = result["intent"]
        intent_path = result["intent_path"]
        print(f"  [PASS] Synthetic intent generated: {intent_path}")
    except Exception as e:
        print(f"  [FAIL] build_email_intent raised: {e}")
        sys.exit(1)

    # Step 5: run validation rules against the intent
    print(f"\n  Running validation rules (mirrors voice_email_gate.ps1)...")
    passed, errors, warnings = validate_intent(intent)

    if errors:
        print(f"\n  [FAIL] {len(errors)} ERROR(S):")
        for e in errors:
            print(f"    ✗ {e}")
    if warnings:
        print(f"\n  [WARN] {len(warnings)} WARNING(S):")
        for w in warnings:
            print(f"    ! {w}")

    if not passed:
        print(f"\n=== ❌ VALIDATION FAILED — fix the errors above and re-run ===\n")
        sys.exit(1)

    print(f"\n  [PASS] All validation rules passed")

    # Step 6 (optional): create a test calendar event
    if "--create-test-calendar" in sys.argv:
        print(f"\n  --create-test-calendar requested. To actually create the calendar event,")
        print(f"  hand off to Claude Code with this command:")
        print(f'    "Use voice-deployer to create a test calendar event for {firm["slug"]} from the synthetic intent."')

    print(f"\n=== ✅ {firm['name']} SETUP VALIDATED — demo-ready ===")
    print(f"\n  Next:")
    print(f"    1. Place a real test call to {phone}")
    print(f"    2. Run: python tools/book_pending_consults.py --firm {firm['slug']}")
    print(f"    3. Have Claude Code dispatch the booking + email intents")
    print(f"    4. Verify calendar event + email landed as expected\n")


if __name__ == "__main__":
    main()
