def test_no_print_statements():
    """Test 8: Are all print() statements gone?"""
    print("\n=== TEST 8: No Remaining print() Calls ===")
    source = Path(__file__).parent / "mcp_server.py"
    content = source.read_text(encoding='utf-8')

    lines_with_print = []
    for i, line in enumerate(content.split('\n'), 1):
        stripped = line.strip()
        # Skip comments and strings
        if stripped.startswith('#'):
            continue
        if 'print(' in stripped and 'file=sys.stderr' in stripped:
            lines_with_print.append((i, stripped[:80]))

    if not lines_with_print:
        print(f"  Zero print(file=sys.stderr) found")
        print("  PASS - All migrated to loguru")
        return True
    else:
        print(f"  FAIL - {len(lines_with_print)} print() calls remain:")
        for line_num, text in lines_with_print[:5]:
            print(f"    Line {line_num}: {text}")
        return False


