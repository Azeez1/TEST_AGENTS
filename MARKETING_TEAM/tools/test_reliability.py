def test_retry_actually_retries():
    """Test 3: Does retry actually retry on failure?"""
    print("\n=== TEST 3: Retry Actually Fires ===")
    from tenacity import retry, stop_after_attempt, wait_exponential, retry_if_exception_type

    call_count = 0

    @retry(
        stop=stop_after_attempt(3),
        wait=wait_exponential(multiplier=0.1, min=0.1, max=0.5),  # Fast for testing
        retry=retry_if_exception_type((Exception,)),
        reraise=True
    )
    async def flaky_function():
        nonlocal call_count
        call_count += 1
        if call_count < 3:
            raise ConnectionError(f"Simulated failure #{call_count}")
        return "success on attempt 3"

    result = asyncio.run(flaky_function())

    if call_count == 3 and result == "success on attempt 3":
        print(f"  Function called {call_count} times (failed 2, succeeded on 3rd)")
        print(f"  Result: {result}")
        print("  PASS - Retry logic works correctly")
        return True
    else:
        print(f"  FAIL - Expected 3 calls, got {call_count}")
        return False


def test_retry_gives_up_after_max():
    """Test 4: Does retry stop after max attempts?"""
    print("\n=== TEST 4: Retry Gives Up After Max ===")
    from tenacity import retry, stop_after_attempt, wait_exponential, retry_if_exception_type

    call_count = 0

    @retry(
        stop=stop_after_attempt(3),
        wait=wait_exponential(multiplier=0.1, min=0.1, max=0.5),
        retry=retry_if_exception_type((Exception,)),
        reraise=True
    )
    async def always_fails():
        nonlocal call_count
        call_count += 1
        raise ConnectionError(f"Permanent failure #{call_count}")

    try:
        asyncio.run(always_fails())
        print("  FAIL - Should have raised exception")
        return False
    except ConnectionError:
        if call_count == 3:
            print(f"  Function called {call_count} times then gave up")
            print(f"  Original exception re-raised correctly")
            print("  PASS - Max retry limit works")
            return True
        else:
            print(f"  FAIL - Expected 3 calls, got {call_count}")
            return False


def test_fallback_chain():
    """Test 5: Does the fallback chain cascade correctly?"""
    print("\n=== TEST 5: Image Fallback Chain ===")
    from mcp.types import TextContent

    call_log = []

    async def mock_nano2(*args, **kwargs):
        call_log.append("Nano Banana 2")
        raise Exception("Google API down")

    async def mock_nanopro(*args, **kwargs):
        call_log.append("Nano Banana Pro")
        raise Exception("Google API still down")

    async def mock_gpt4o(*args, **kwargs):
        call_log.append("GPT-4o")
        return [TextContent(type="text", text="Generated by GPT-4o fallback")]

    with patch('tools.mcp_server.generate_nano_banana_2_image_mcp', mock_nano2), \
         patch('tools.mcp_server.generate_nano_banana_image_mcp', mock_nanopro), \
         patch('tools.mcp_server.generate_gpt4o_image_mcp', mock_gpt4o):

        from tools.mcp_server import generate_image_with_fallback
        result = asyncio.run(generate_image_with_fallback(
            prompt="test", aspect_ratio="16:9", filename="test.png"
        ))

    if call_log == ["Nano Banana 2", "Nano Banana Pro", "GPT-4o"]:
        print(f"  Call order: {' -> '.join(call_log)}")
        print(f"  Final result from: GPT-4o (3rd provider)")
        print("  PASS - Fallback chain cascades correctly")
        return True
    else:
        print(f"  FAIL - Unexpected call order: {call_log}")
        return False


